// apps/docs/scripts/gen-component-index.mjs
//
// Generates the "Find the code" component index from the repo-root component-map.json
// (the single cross-surface source produced by `bun run gen:component-map`). Runs before
// every astro dev/build, so the page is always in step with the map and never hand-edited.
// Output is gitignored (mirrors the starlight-typedoc api/ pattern).

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
const mapPath = join(repoRoot, 'component-map.json');
const outPath = join(here, '..', 'src', 'content', 'docs', 'design-system', 'components.mdx');

if (!existsSync(mapPath)) {
  // Don't fail the docs build if the map hasn't been generated — emit a stub that says so.
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(
    outPath,
    `---\ntitle: Find the code\ndescription: Component ↔ code ↔ Ladle ↔ Figma ↔ Claude Design index.\n---\n\n` +
      `:::caution\n\`component-map.json\` not found — run \`bun run gen:component-map\` at the repo root.\n:::\n`,
    'utf8',
  );
  console.log('[gen-component-index] component-map.json missing — wrote stub.');
  process.exit(0);
}

const map = JSON.parse(readFileSync(mapPath, 'utf8'));
const { components, claudeDesignProject, figmaFileKey } = map;
const storyless = components.filter((c) => !c.ladleStoryId).map((c) => c.name);

const figmaFileUrl = `https://www.figma.com/design/${figmaFileKey}`;

const rows = components
  .map((c) => {
    const code = c.githubUrl ? `[\`${c.codePath.split('/').pop()}\`](${c.githubUrl})` : '—';
    const figma = c.figmaNodeId ? `[\`${c.figmaNodeId}\`](${c.figmaUrl})` : '—';
    const story = c.ladleStoryId ? `\`${c.ladleStoryId}\`` : '—';
    return `| **${c.name}** | ${code} | ${figma} | ${story} |`;
  })
  .join('\n');

const mdx = `---
title: Find the code
description: One generated index linking every oj-ui component across code, Ladle, Figma, and Claude Design — the free-tier bridge that replaces Code Connect.
---

import { Aside, LinkCard, CardGrid } from '@astrojs/starlight/components';

{/* GENERATED by apps/docs/scripts/gen-component-index.mjs from the repo-root component-map.json.
    DO NOT EDIT — run \`bun run gen:component-map\` then rebuild the docs. */}

The canonical, drift-free map from a component to its code, its live preview, and its Figma master.
On free Figma there are no Dev-Mode code snippets (Code Connect needs Org/Enterprise), so **this page
is the bridge**: it's generated at build time from \`component-map.json\`, so it can never go stale.

<CardGrid>
  <LinkCard title="Browse the live components" description="claude.ai/design — every component, rendered and composable." href="${claudeDesignProject ?? 'https://claude.ai/design'}" />
  <LinkCard title="Open the Figma library" description="The oj-ui Figma file (set to link-viewable)." href="${figmaFileUrl}" />
</CardGrid>

<Aside type="tip">
**Run the component workbench locally:** \`bun run ladle\` (opens at \`localhost:61000\`), then open the
listed story id. The **Story** column is the Ladle story id; the **Code** column is the source on
GitHub; the **Figma** column deep-links the component master's node.
</Aside>

## Components (${components.length})

| Component | Code | Figma | Ladle story |
| --- | --- | --- | --- |
${rows}

${
  storyless.length
    ? `<Aside type="note">\n${storyless.length} component(s) have no Ladle story yet (${storyless
        .map((n) => `\`${n}\``)
        .join(', ')}). They still render on claude.ai/design and have a Figma master + code link.\n</Aside>`
    : ''
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, mdx, 'utf8');
console.log(
  `[gen-component-index] wrote ${components.length} components (${storyless.length} storyless).`,
);
